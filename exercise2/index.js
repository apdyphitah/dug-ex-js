let a = 15
let b = "15"

// equal to operator (==) checks for value equality
console.log(a == b) // true

console.log(a != b) // true
// strict equal to operator (===) checks for both value and type equality
console.log(a === b) // false
console.log(a !== b) // true

// greater than operator (>)
console.log(a > b) // false
// less than operator (<)
console.log(a < b) // false     
// greater than or equal to operator (>=)
console.log(a >= b) // true
// less than or equal to operator (<=)
console.log(a <= b) // true